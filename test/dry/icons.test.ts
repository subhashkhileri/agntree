import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'fs';
import * as path from 'path';
import { ClaudeHarness } from '../../src/harnesses/ClaudeHarness';
import { OpencodeHarness } from '../../src/harnesses/OpencodeHarness';
import { CodexHarness } from '../../src/harnesses/CodexHarness';
import { harnessTreeIcons } from '../../src/harnesses/treeIcons';

const ROOT = path.resolve(__dirname, '..', '..', '..');
const adapters = [new ClaudeHarness(), new OpencodeHarness(), new CodexHarness()];
const read = (relative: string) => fs.readFileSync(path.join(ROOT, relative), 'utf8');

test('every harness ships generated marks for every theme and state', () => {
  for (const adapter of adapters) {
    assert.deepEqual(adapter.treeIcons, harnessTreeIcons(adapter.id), `${adapter.id} uses the generated paths`);
    for (const theme of ['light', 'dark'] as const) {
      for (const [state, relative] of Object.entries(harnessTreeIcons(adapter.id)[theme])) {
        assert.match(
          read(relative),
          /<!-- generated by scripts\/generate-harness-icons\.mjs -->/,
          `${adapter.id} ${theme} ${state} is generated, not hand-edited`
        );
      }
    }
  }
});

test('state marks: working animates (honoring reduced motion), done is a green dot, closed is grey, new is a ring', () => {
  for (const adapter of adapters) {
    const icons = harnessTreeIcons(adapter.id).light;
    const working = read(icons.working);
    assert.match(working, /@keyframes/);
    assert.match(working, /prefers-reduced-motion/);
    assert.doesNotMatch(working, /cx="18\.2"/, `${adapter.id} working mark carries no badge`);

    const done = read(icons.done);
    assert.match(done, /fill="#2f9e44"/);
    assert.doesNotMatch(done, /@keyframes/, `${adapter.id} done mark is static`);

    const closed = read(icons.closed);
    assert.match(closed, /fill="#8a8a8a"/);
    assert.doesNotMatch(closed, /cx="18\.2"/, `${adapter.id} closed mark has no badge`);

    assert.match(read(icons.new), /stroke="#8a8a8a"/, `${adapter.id} new mark is a hollow ring`);
  }
});
