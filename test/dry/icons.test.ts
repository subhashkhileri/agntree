import * as fs from 'fs';
import * as path from 'path';
import { ClaudeHarness } from '../../src/harnesses/ClaudeHarness';
import { OpencodeHarness } from '../../src/harnesses/OpencodeHarness';
import { harnessTreeIcons } from '../../src/harnesses/treeIcons';
import { selectHarnessIconState } from '../../src/harnesses/sessionUtils';
import { ChatSession, HarnessId } from '../../src/types';

const ROOT = path.resolve(__dirname, '..', '..', '..');
const STATES = ['running', 'closed', 'new'] as const;
const THEMES = ['light', 'dark'] as const;

let failures = 0;
function check(condition: boolean, message: string): void {
  if (condition) {
    console.log(`PASS  ${message}`);
  } else {
    failures++;
    console.error(`FAIL  ${message}`);
  }
}

function chat(overrides: Partial<ChatSession> = {}): ChatSession {
  return {
    id: 'chat-1',
    worktreeId: 'wt-1',
    name: 'Session',
    harness: 'claude',
    harnessSessionId: null,
    createdAt: 1,
    lastAccessedAt: 1,
    status: 'idle',
    baseCommit: null,
    ...overrides,
  };
}

async function main(): Promise<void> {
  console.log('\n== generated files ==');
  const harnesses: { id: HarnessId; adapter: ClaudeHarness | OpencodeHarness }[] = [
    { id: 'claude', adapter: new ClaudeHarness() },
    { id: 'opencode', adapter: new OpencodeHarness() },
  ];

  for (const { id, adapter } of harnesses) {
    const icons = harnessTreeIcons(id);
    check(Boolean(adapter.treeIcons), `${id} adapter exposes tree icons`);
    check(
      JSON.stringify(adapter.treeIcons) === JSON.stringify(icons),
      `${id} paths match the generated file convention`
    );

    for (const theme of THEMES) {
      for (const state of STATES) {
        const relative = icons[theme][state];
        const file = path.join(ROOT, relative);
        const exists = fs.existsSync(file);
        check(exists, `${id} ${theme} ${state}: ${relative}`);
        if (!exists) {
          continue;
        }

        const svg = fs.readFileSync(file, 'utf8');
        check(
          svg.includes('<!-- generated by scripts/generate-harness-icons.mjs -->'),
          `${id} ${theme} ${state} is generated, not hand-edited`
        );
        check(svg.includes('<svg'), `${id} ${theme} ${state} is an SVG`);
      }
    }

    const running = fs.readFileSync(path.join(ROOT, icons.light.running), 'utf8');
    const closed = fs.readFileSync(path.join(ROOT, icons.light.closed), 'utf8');
    const fresh = fs.readFileSync(path.join(ROOT, icons.light.new), 'utf8');
    check(running.includes('fill="#2f9e44"'), `${id} running badge is green`);
    check(
      closed.includes('fill="#8a8a8a"') && !closed.includes('cx="18.2"'),
      `${id} closed mark is grey and has no badge`
    );
    check(
      fresh.includes('stroke="#8a8a8a"'),
      `${id} new badge is a hollow ring`
    );
  }

  console.log('\n== state selection ==');
  check(selectHarnessIconState(chat(), true) === 'running', 'active terminal wins');
  check(
    selectHarnessIconState(
      chat({ status: 'closed', harnessSessionId: 'abc' }),
      false
    ) === 'closed',
    'closed status with a session uses the closed variant'
  );
  check(
    selectHarnessIconState(chat({ harnessSessionId: 'abc' }), false) === 'closed',
    'session without an open terminal is closed'
  );
  check(
    selectHarnessIconState(
      chat({ status: 'active', harnessSessionId: 'abc' }),
      false
    ) === 'closed',
    'stale active status without a terminal is closed'
  );
  check(
    selectHarnessIconState(chat({ harnessSessionId: null }), false) === 'new',
    'unlinked chat uses the new variant'
  );
  check(
    selectHarnessIconState(chat({ status: 'closed' }), true) === 'running',
    'running outranks closed'
  );

  console.log(
    `\n${failures === 0 ? 'ALL HARNESS ICON CHECKS PASSED' : `${failures} FAILURE(S)`}`
  );
  process.exit(failures === 0 ? 0 : 1);
}

main().catch((error) => {
  console.error('UNEXPECTED FAILURE', error);
  process.exit(1);
});
